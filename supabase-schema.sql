-- NILUS RESTAURANT - SUPABASE DATABASE SETUP
-- Step 1: run this whole file in Supabase SQL Editor.
-- After creating your first Auth user, copy that user's UUID into manager_profiles.

create table if not exists public.categories (
    id bigint generated by default as identity primary key,
    name text not null unique,
    description text,
    image_url text,
    display_order integer not null default 0,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.menu_items (
    id bigint generated by default as identity primary key,
    category_id bigint not null references public.categories(id) on delete cascade,
    name text not null,
    description text,
    price numeric(10,2) not null check (price >= 0),
    image_url text,
    available boolean not null default true,
    display_order integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.manager_profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    role text not null default 'manager' check (role in ('manager', 'admin')),
    created_at timestamptz not null default now()
);

create index if not exists menu_items_category_id_idx on public.menu_items(category_id);
create index if not exists categories_display_order_idx on public.categories(display_order);
create index if not exists menu_items_display_order_idx on public.menu_items(display_order);

-- Automatically update updated_at whenever a row changes.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists categories_set_updated_at on public.categories;
create trigger categories_set_updated_at
before update on public.categories
for each row execute function public.set_updated_at();

drop trigger if exists menu_items_set_updated_at on public.menu_items;
create trigger menu_items_set_updated_at
before update on public.menu_items
for each row execute function public.set_updated_at();

-- Used by RLS policies to identify a manager/admin.
create or replace function public.is_manager()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.manager_profiles
    where user_id = auth.uid()
  );
$$;

revoke all on function public.is_manager() from public;
grant execute on function public.is_manager() to authenticated;

alter table public.categories enable row level security;
alter table public.menu_items enable row level security;
alter table public.manager_profiles enable row level security;

-- Clean up policies if this script is run more than once.
drop policy if exists "Public can read active categories" on public.categories;
drop policy if exists "Managers can read all categories" on public.categories;
drop policy if exists "Managers can create categories" on public.categories;
drop policy if exists "Managers can update categories" on public.categories;
drop policy if exists "Managers can delete categories" on public.categories;

drop policy if exists "Public can read available menu items" on public.menu_items;
drop policy if exists "Managers can read all menu items" on public.menu_items;
drop policy if exists "Managers can create menu items" on public.menu_items;
drop policy if exists "Managers can update menu items" on public.menu_items;
drop policy if exists "Managers can delete menu items" on public.menu_items;

drop policy if exists "Managers can read their role" on public.manager_profiles;

-- Customers only see active categories.
create policy "Public can read active categories"
on public.categories
for select
to anon, authenticated
using (active = true);

-- Managers can see inactive categories too.
create policy "Managers can read all categories"
on public.categories
for select
to authenticated
using (public.is_manager());

create policy "Managers can create categories"
on public.categories
for insert
to authenticated
with check (public.is_manager());

create policy "Managers can update categories"
on public.categories
for update
to authenticated
using (public.is_manager())
with check (public.is_manager());

create policy "Managers can delete categories"
on public.categories
for delete
to authenticated
using (public.is_manager());

-- Customers only see available food inside active categories.
create policy "Public can read available menu items"
on public.menu_items
for select
to anon, authenticated
using (
  available = true
  and exists (
    select 1 from public.categories c
    where c.id = category_id and c.active = true
  )
);

-- Managers can see unavailable food too.
create policy "Managers can read all menu items"
on public.menu_items
for select
to authenticated
using (public.is_manager());

create policy "Managers can create menu items"
on public.menu_items
for insert
to authenticated
with check (public.is_manager());

create policy "Managers can update menu items"
on public.menu_items
for update
to authenticated
using (public.is_manager())
with check (public.is_manager());

create policy "Managers can delete menu items"
on public.menu_items
for delete
to authenticated
using (public.is_manager());

-- A manager can see their own manager role row.
create policy "Managers can read their role"
on public.manager_profiles
for select
to authenticated
using (user_id = auth.uid());

-- Explicit API grants. RLS policies above still control which rows can be used.
revoke all on public.categories from anon, authenticated;
revoke all on public.menu_items from anon, authenticated;
revoke all on public.manager_profiles from anon, authenticated;

grant select on public.categories to anon, authenticated;
grant select on public.menu_items to anon, authenticated;
grant select on public.manager_profiles to authenticated;
grant insert, update, delete on public.categories to authenticated;
grant insert, update, delete on public.menu_items to authenticated;

grant usage, select on all sequences in schema public to authenticated;

-- ------------------------------------------------------------
-- STORAGE: MENU IMAGES
-- Create a bucket named "menu-images" in Storage first.
-- The bucket is public because customers must be able to view menu images.
-- Only managers can upload, replace, or delete files.
-- ------------------------------------------------------------

drop policy if exists "Anyone can view menu images" on storage.objects;
drop policy if exists "Managers can upload menu images" on storage.objects;
drop policy if exists "Managers can update menu images" on storage.objects;
drop policy if exists "Managers can delete menu images" on storage.objects;

create policy "Anyone can view menu images"
on storage.objects
for select
to public
using (bucket_id = 'menu-images');

create policy "Managers can upload menu images"
on storage.objects
for insert
to authenticated
with check (bucket_id = 'menu-images' and public.is_manager());

create policy "Managers can update menu images"
on storage.objects
for update
to authenticated
using (bucket_id = 'menu-images' and public.is_manager())
with check (bucket_id = 'menu-images' and public.is_manager());

create policy "Managers can delete menu images"
on storage.objects
for delete
to authenticated
using (bucket_id = 'menu-images' and public.is_manager());

